"""The Docker development stack: the whole fleet on one machine, until a real platform is available.

`docker/compose.yml` is rendered from ecosystem.yaml (`ecoctl dev render`; a test fails when the file and the manifest drift apart). It holds only what
is not secret: images, ports, public URLs, model aliases, the OIDC client ids. Every secret travels the way it does in the fleet:

* each app starts **sealed** (agentpg-kit `apgkit.sealed`): one blob, encrypted under the operator's passphrase, holds its database URL, its generated
  secrets, its identity client secret and its gateway key. Compose gets the blob as a *secret whose source is an environment variable of the
  `docker compose` process*: nothing is written to the host's disk, and in the container it appears as a file under /run/secrets (APGKIT_SEALED_FILE),
  not in the container's environment. After start the operator's passphrase is sent encrypted to the app (`ecoctl dev unseal`, the same code as
  `ecoctl unseal`), which opens the blob, migrates and serves.
* the Postgres superuser password and the EDB repository token (image build only) travel the same way, as compose secrets sourced from the environment.
* one database and one login role per app; the role is not a superuser and owns only its database. Its password is generated, kept in the encrypted
  state file (.ecosystem-dev/state.json, the same format as ecoctl's) and set over the container's stdin: it is in no compose file.

Every address is `http://<app>.localhost:<port>`: the browser resolves `*.localhost` to loopback, and the compose network gives each service that name as an
alias, so the issuer URL a token carries is the same from the browser, from ecoctl on the host and from the other containers. (Apps accept plain http only
for localhost hosts.)
"""
import os
import re
import secrets
import subprocess
import tempfile
import time
from collections.abc import Callable
from pathlib import Path

import httpx
import yaml
from apgkit import sealed as kit

from . import seal
from .connect import connect_step
from .llm_client import GatewayError
from .manifest import App, Manifest
from .plan import Context, _register, _register_ecoctl, app_env
from .state import State

DEV_STATE_DIR = Path(".ecosystem-dev")
PORTS = {"identity": 8101, "llmgw": 8102, "trustdesk": 8103, "pagerlens": 8104, "paybroker": 8105, "citypulse": 8106, "cpsim": 8107, "shopfront": 8108}
POSTGRES_HOST_PORT = 55460
# the sibling repository each image is built from (context ../../<repo> from docker/compose.yml)
REPOS = {"identity": "identity", "llmgw": "llm-gateway", "trustdesk": "trustdesk", "pagerlens": "pagerlens", "paybroker": "paybroker",
         "citypulse": "CityPulse", "cpsim": "CityPulseSimulator", "shopfront": "shopfront"}
# apps whose role gets `aidb_users` (and whose database gets the aidb extension): the ones that use AIDB. The others get neither (least privilege).
AIDB_APPS = frozenset({"trustdesk", "pagerlens", "citypulse", "cpsim"})
# extensions the manifest lists for a managed instance that the local image does not have (EDB platform extensions, PostGIS): skipped, the apps degrade without them
NOT_IN_IMAGE = frozenset({"query_advisor", "edb_stat_monitor", "edb_pg_tuner", "postgis", "postgis_raster", "postgis_sfcgal", "postgis_tiger_geocoder", "postgis_topology"})
# apps whose repository cannot boot sealed yet (checked 2026-11-04): skipped unless asked for with `--include`. The reason is printed on every `up`.
NOT_SEALABLE = {"citypulse": "CityPulse 1f5b6d6: `citypulse start` migrates before the app is unsealed and `serve` never migrates afterwards, so it cannot start from a blob alone"}
DB_NAME = re.compile(r"^[a-z][a-z0-9_]{1,30}$")
SUPERUSER_ENV = "PG_SUPERUSER_PASSWORD"
EDB_TOKEN_ENV = "EDB_SUBSCRIPTION_TOKEN"
# a real provider for the gateway, from the operator's environment (nothing is read from a file; none set: the gateway keeps its built-in echo provider)
PROVIDER_ENV = {"url": "ECOCTL_DEV_LLM_BASE_URL", "key": "ECOCTL_DEV_LLM_API_KEY", "chat": "ECOCTL_DEV_LLM_CHAT_MODEL", "embed": "ECOCTL_DEV_LLM_EMBED_MODEL"}
PROVIDER_NAME = "dev-provider"
HEADER = ("# GENERATED by `ecoctl dev render` from ecosystem.yaml: do not edit (a test fails when it drifts from the manifest).\n"
          "# No secret is in this file: every app starts sealed and gets its blob as a compose secret taken from the environment of `ecoctl dev up`.\n"
          "# Read docker/README.md before running `docker compose` by hand.\n")


class DevError(RuntimeError):
    pass


def url_of(key: str) -> str:
    return f"http://{key}.localhost:{PORTS[key]}"


def deployed(m: Manifest) -> list[App]:
    """The apps the stack runs, in start order: identity, then every app after what it needs (the gateway before its clients)."""
    return [m.identity, *[a for a in m.order() if a.deploy]]


def check_ports(m: Manifest) -> None:
    missing = [a.key for a in deployed(m) if a.key not in PORTS or a.key not in REPOS]
    if missing:
        raise DevError(f"the Docker stack has no port or repository for: {', '.join(missing)} (add them to devstack.PORTS and REPOS)")


def blob_var(key: str) -> str:
    return f"SEALED_{key.upper()}"


def role_password_name() -> str:
    return "DB_PASSWORD"


# ---- the compose file --------------------------------------------------------------------------------------------------------------------------
def dummy_context(m: Manifest, scratch: Path) -> Context:
    """A context that knows every URL and pretends every secret exists, to learn which names an app's environment has and which are secret."""
    st = State(scratch)
    for a in deployed(m):
        e = st.app(a.key)
        e["url"] = url_of(a.key)
        e["client_secret"] = e["service_secret"] = e["llm_key"] = "x"
    return Context(m, st, None)                                                    # type: ignore[arg-type]  (no AgentPG: nothing here calls it)


def public_env(ctx: Context, app: App) -> tuple[dict[str, str], set[str]]:
    """(the non-secret environment of the app's container, the secret names that go into its sealed blob)."""
    env, secret_names = app_env(ctx, app)
    public = {k: v for k, v in env.items() if k not in secret_names and k != app.encryption_key_name}
    public["PORT"] = str(PORTS[app.key])
    if app.key == "identity":
        public["IDENTITY_PUBLIC_URL"] = url_of("identity")
    elif app.web:
        public[f"{app.env_prefix}_PUBLIC_URL"] = url_of(app.key)
    public["APGKIT_SEALED_FILE"] = "/run/secrets/apgkit_sealed"
    return dict(sorted(public.items())), secret_names - {app.encryption_key_name}


def database_spec(m: Manifest) -> list[str]:
    """`name:aidb(0|1):ext,ext` for each app, the format docker/initdb/20-app-databases.sh reads from APP_DATABASES."""
    out = []
    for a in deployed(m):
        if not DB_NAME.match(a.key):
            raise DevError(f"{a.key!r} cannot be a database or role name")
        exts = sorted(e for e in a.extensions if e not in NOT_IN_IMAGE)
        out.append(f"{a.key}:{int(a.key in AIDB_APPS)}:{','.join(exts)}")
    return out


def render(m: Manifest) -> str:
    check_ports(m)
    apps = deployed(m)
    with tempfile.TemporaryDirectory() as tmp:
        ctx = dummy_context(m, Path(tmp))
        envs = {a.key: public_env(ctx, a)[0] for a in apps}
    services: dict = {"postgres": {
        "image": "aidb-postgres:17",
        "build": {"context": "./aidb-postgres", "secrets": ["edb_token"]},
        "environment": {"POSTGRES_PASSWORD_FILE": "/run/secrets/pg_superuser", "APP_DATABASES": " ".join(database_spec(m))},
        "secrets": [{"source": "pg_superuser", "target": "pg_superuser"}],
        "volumes": ["pgdata:/var/lib/postgresql/data", "./initdb/20-app-databases.sh:/docker-entrypoint-initdb.d/20-app-databases.sh:ro"],
        "ports": [f"127.0.0.1:{POSTGRES_HOST_PORT}:5432"],
        "healthcheck": {"test": ["CMD-SHELL", "pg_isready -h 127.0.0.1 -U postgres"], "interval": "3s", "timeout": "3s", "retries": 40},
        "restart": "unless-stopped",
    }}
    for a in apps:
        needs = [m.identity.key, *sorted(m.needs(a.key))] if a.key != "identity" else []
        depends = {"postgres": {"condition": "service_healthy"}, **{k: {"condition": "service_healthy"} for k in needs}}
        services[a.key] = {
            "image": f"ecosystem-dev/{a.key}:dev",
            "build": {"context": f"../../{REPOS[a.key]}"},
            "environment": envs[a.key],
            "secrets": [{"source": f"sealed_{a.key}", "target": "apgkit_sealed"}],
            "ports": [f"127.0.0.1:{PORTS[a.key]}:{PORTS[a.key]}"],
            "networks": {"default": {"aliases": [f"{a.key}.localhost"]}},
            "depends_on": depends,
            "cap_drop": ["ALL"],
            "security_opt": ["no-new-privileges:true"],
            "restart": "unless-stopped",
        }
    secrets_ = {"edb_token": {"environment": EDB_TOKEN_ENV}, "pg_superuser": {"environment": SUPERUSER_ENV},
                **{f"sealed_{a.key}": {"environment": blob_var(a.key)} for a in apps}}
    doc = {"name": "ecosystem-dev", "services": services, "secrets": secrets_, "volumes": {"pgdata": {}}}
    return HEADER + yaml.safe_dump(doc, sort_keys=False, width=200)


# ---- the stack -----------------------------------------------------------------------------------------------------------------------------
class Stack:
    def __init__(self, ctx: Context, compose_file: Path, say: Callable[[str], None] | None = None,
                 run: Callable[..., subprocess.CompletedProcess] | None = None, sleep: Callable[[float], None] = time.sleep, include: set[str] | None = None):
        self.ctx, self.m, self.file = ctx, ctx.manifest, Path(compose_file)
        self.skipped = {k: why for k, why in NOT_SEALABLE.items() if k not in (include or set())}
        self.say = say or (lambda text: print(text, flush=True))
        self._run, self.sleep = run or subprocess.run, sleep

    def active(self) -> list[App]:
        return [a for a in deployed(self.m) if a.key not in self.skipped]

    # -- docker compose, with secrets only in the child's environment --
    def compose(self, *args: str, env: dict[str, str] | None = None, stdin: str | None = None, check: bool = True, quiet: bool = True) -> subprocess.CompletedProcess:
        cmd = ["docker", "compose", "-f", str(self.file), *args]
        r = self._run(cmd, env={**os.environ, **(env or {})}, input=stdin, text=True, capture_output=quiet, check=False)
        if check and r.returncode != 0:
            tail = (r.stderr or r.stdout or "")[-600:]
            raise DevError(f"`docker compose {' '.join(args[:3])}` failed (exit {r.returncode}): {tail.strip()}")
        return r

    def container_state(self, key: str) -> str | None:
        """running, exited, ... or None when the container does not exist."""
        r = self.compose("ps", "-a", "--format", "{{.State}}", key, check=False)
        text = (r.stdout or "").strip()
        return text.splitlines()[0] if text else None

    def check_compose_current(self) -> None:
        if not self.file.exists() or self.file.read_text() != render(self.m):
            raise DevError(f"{self.file} does not match the manifest: run `ecoctl dev render`")

    # -- postgres --
    def super_env(self) -> dict[str, str]:
        return {SUPERUSER_ENV: self.ctx.state.secret("postgres", SUPERUSER_ENV)}

    def database_url(self, key: str) -> str:
        return f"postgresql://{key}:{self.ctx.state.secret(key, role_password_name())}@postgres:5432/{key}?sslmode=disable"

    def start_postgres(self, build: bool) -> None:
        env = self.super_env()
        have = self._run(["docker", "image", "inspect", "aidb-postgres:17"], capture_output=True, text=True, check=False).returncode == 0
        if not have:
            if not build:
                raise DevError("the aidb-postgres:17 image does not exist and --no-build was given")
            if not os.environ.get(EDB_TOKEN_ENV):
                raise DevError(f"the aidb-postgres:17 image does not exist yet and building it needs the EDB repository token in {EDB_TOKEN_ENV} (BuildKit secret, never stored): "
                               "see docker/README.md")
            self.say("  building aidb-postgres:17 (the EDB token is a BuildKit secret)")
            self.compose("build", "postgres", env={EDB_TOKEN_ENV: os.environ[EDB_TOKEN_ENV]})
        self.compose("up", "-d", "--wait", "--wait-timeout", "180", "postgres", env=env)
        # idempotent: databases and roles for apps added after the volume was first initialised (the init script itself only runs once)
        self.compose("exec", "-T", "-u", "postgres", "postgres", "bash", "/docker-entrypoint-initdb.d/20-app-databases.sh")
        for a in deployed(self.m):
            pw = self.ctx.state.secret(a.key, role_password_name())
            self.compose("exec", "-T", "-u", "postgres", "postgres", "psql", "-v", "ON_ERROR_STOP=1", "-q", "-U", "postgres", "-d", "postgres",
                         stdin=f"ALTER ROLE {a.key} PASSWORD '{pw}';\n")                      # on stdin only: not in a file, an argument or the environment
        self.ctx.state.save()

    # -- apps --
    def blob(self, app: App) -> str:
        env, secret_names = app_env(self.ctx, app)
        payload = {k: v for k, v in env.items() if k in secret_names and k != app.encryption_key_name}
        payload["DATABASE_URL"] = self.database_url(app.key)
        return kit.seal(payload, seal.passphrase(self.ctx, creating=False))

    def start_app(self, app: App, build: bool, recreate: bool) -> str:
        st = self.container_state(app.key)
        if st == "running" and not recreate:
            return "running"
        if st and not recreate:
            self.compose("start", app.key)
            return f"started (was {st})"
        env = {blob_var(app.key): self.blob(app), **self.super_env()}
        self.compose("up", "-d", "--no-deps", *(["--build"] if build else []), *(["--force-recreate"] if recreate else []), app.key, env=env)
        return "created"

    def wait_alive(self, app: App, timeout: float = 240) -> None:
        """A sealed app answers /_seal/status (and /healthz) before anything else: wait for that."""
        deadline = time.monotonic() + timeout
        while seal.state_of(url_of(app.key), self.ctx.http) is None:
            if time.monotonic() > deadline:
                raise DevError(f"{app.key} did not answer {url_of(app.key)}/_seal/status within {int(timeout)} s: `docker compose -f {self.file} logs {app.key}`")
            self.sleep(2)

    def unseal(self, app: App) -> str:
        self.wait_alive(app)
        return seal.unseal(self.ctx, app)

    def up(self, *, build: bool = True, recreate: set[str] | None = None) -> None:
        m, st = self.m, self.ctx.state
        recreate = recreate or set()
        check_ports(m)
        self.check_compose_current()
        st.require_passphrase()
        for a in deployed(m):
            st.app(a.key)["url"] = url_of(a.key)
        t0 = time.monotonic()
        self.say("postgres: start, databases and roles")
        self.start_postgres(build)
        for key, why in self.skipped.items():
            self.say(f"SKIPPED {key}: {why} (--include {key} to try anyway)")
        for app in self.active():
            self.say(f"{app.key}:")
            if app.key == "identity":
                self.say(f"  container {self.start_app(app, build, app.key in recreate)}")
                self.say(f"  {self.unseal(app)}")
                ident = self.ctx.identity()
                ident.wait_ready()
                self.say(f"  issuer {ident.pin_issuer()}")
                continue
            self.say(f"  identity: {_register(self.ctx, app)}")
            if app.llm:
                self.say(f"  gateway: {self.llm_client(app)}")
            self.say(f"  container {self.start_app(app, build, app.key in recreate)}")
            self.say(f"  {self.unseal(app)}")
            if app.web:
                self.ctx.identity().set_urls(app.key, url_of(app.key))
            if app.key == m.llm.gateway:
                self.say(f"  {self.provider_step()}")
        self.groups()
        self.connections()
        self.dev_user()
        self.say(f"stack is up ({time.monotonic() - t0:.0f} s). Addresses: " + ", ".join(f"{a.key} {url_of(a.key)}" for a in deployed(m)))

    def llm_client(self, app: App) -> str:
        """Same as plan._llm_client; the gateway is reached at its own URL (the container is already unsealed: the apps come after it in the order)."""
        from .plan import _llm_client
        return _llm_client(self.ctx, app)

    def provider_step(self) -> str:
        return ensure_provider(self.ctx.gateway(), os.environ, self.m.llm.chat_alias, self.m.llm.embed_alias)

    def groups(self) -> None:
        """plan._group, limited to the apps that are running (a skipped app has no client to grant a role on)."""
        ident, live = self.ctx.identity(), {a.key: a for a in self.active() if a.web}
        for g in self.m.groups:
            ident.ensure_group(g.name, g.description)
            done = 0
            for target, role in g.grants.items():
                keys = [k for k, a in live.items() if role in {r.name for r in a.roles}] if target == "*" else [k for k in [target] if k in live]
                done += sum(ident.ensure_grant(g.name, k, role) for k in keys)
            self.say(f"group {g.name}: {done} grant(s) added")

    def connections(self) -> None:
        m = self.m
        pairs = [(a, peer) for a in m.order() if a.deploy for peer in a.connect]
        if not pairs:
            return
        self.say(f"ecoctl: {_register_ecoctl(self.ctx)}")
        for a, peer in pairs:
            self.say(f"{a.key} -> {peer}: {connect_step(self.ctx, a.key, peer)}")

    def dev_user(self) -> None:
        """One person to sign in with: `dev-admin`, in the group that holds admin everywhere. Its password is generated, kept in the encrypted state file
        and shown only by `ecoctl dev password`."""
        st, ident = self.ctx.state, self.ctx.identity()
        users = {u["username"] for u in ident._call("GET", "/api/users")}                # noqa: SLF001  (the client has no user helpers: this is the one call)
        pw = st.data.setdefault("dev", {}).setdefault("admin_password", secrets.token_urlsafe(18))
        if "dev-admin" not in users:
            ident._call("POST", "/api/users", json={"username": "dev-admin", "email": "dev-admin@example.org", "name": "Dev Admin", "password": pw,
                                                     "groups": [g.name for g in self.m.groups if "*" in g.grants]})            # noqa: SLF001
            self.say("user dev-admin created (password: `ecoctl dev password`)")
        st.save()

    def status(self) -> int:
        bad = 0
        for a in self.active():
            cs = self.container_state(a.key) or "absent"
            ss = seal.state_of(url_of(a.key), self.ctx.http) if cs == "running" else None
            ok = cs == "running" and ss in {"unsealed", "disabled"}
            bad += not ok
            self.say(f"{a.key:<10} {cs:<9} {ss or '-':<9} {url_of(a.key)}")
        return 1 if bad else 0

    def down(self, volumes: bool) -> None:
        self.compose("down", *(["-v"] if volumes else []), "--remove-orphans")
        if volumes:
            p = self.ctx.state.path
            if p.exists():
                p.unlink()                                      # its secrets belonged to the volumes just removed


def ensure_provider(gw, environ, chat_alias: str = "chat-default", embed_alias: str = "embed-default") -> str:
    """Point the gateway's default aliases at a real provider when the operator exported a key (ECOCTL_DEV_LLM_API_KEY, and optionally _BASE_URL, _CHAT_MODEL,
    _EMBED_MODEL). The key goes straight from the environment to the gateway's vault. Without it the aliases stay on the built-in echo provider. Run again: nothing changes
    while the provider exists; to change it, use the gateway's UI."""
    key = environ.get(PROVIDER_ENV["key"], "")
    if not key:
        return f"no {PROVIDER_ENV['key']} set: the aliases stay on the built-in echo provider"
    existing = {p["name"] for p in gw._call("GET", "/api/providers")["items"]}               # noqa: SLF001
    if PROVIDER_NAME in existing:
        return f"provider {PROVIDER_NAME} already exists (kept)"
    base = environ.get(PROVIDER_ENV["url"], "https://api.openai.com/v1")
    pid = gw._call("POST", "/api/providers", json={"name": PROVIDER_NAME, "kind": "openai", "base_url": base, "api_key": key, "enabled": True})["id"]     # noqa: SLF001
    models = {m["alias"]: m for m in gw._call("GET", "/api/models")["items"]}                # noqa: SLF001
    for alias, kind, upstream in ((chat_alias, "chat", environ.get(PROVIDER_ENV["chat"], "gpt-4o-mini")),
                                  (embed_alias, "embedding", environ.get(PROVIDER_ENV["embed"], "text-embedding-3-small"))):
        cur = models.get(alias, {})
        body = {"kind": kind, "description": cur.get("description", ""), "enabled": True, "targets": [{"provider_id": pid, "upstream_model": upstream}]}
        if kind == "embedding" and cur.get("embedding_dim"):
            body["embedding_dim"] = cur["embedding_dim"]
        gw._call("PUT", f"/api/models/{alias}", json=body)                                    # noqa: SLF001
    return f"provider {PROVIDER_NAME} added at {base}; the default chat and embedding aliases now use it"


# ---- the smoke test -------------------------------------------------------------------------------------------------------------------------
def smoke(stack: Stack) -> list[tuple[str, bool, str]]:
    """Read-mostly checks of a running stack. Returns (name, ok, detail) lines."""
    ctx, m = stack.ctx, stack.m
    http = ctx.http or httpx.Client(timeout=30, follow_redirects=False)
    out: list[tuple[str, bool, str]] = []

    def check(name, fn):
        try:
            ok, detail = fn()
        except (httpx.HTTPError, GatewayError, KeyError, ValueError, DevError, seal.SealError) as exc:
            ok, detail = False, f"{type(exc).__name__}: {str(exc)[:120]}"
        out.append((name, ok, detail))

    for a in stack.active():
        def alive(a=a):
            s = seal.state_of(url_of(a.key), http)
            r = http.get(url_of(a.key) + "/healthz")
            return s in {"unsealed", "disabled"} and r.status_code == 200, f"seal={s} healthz={r.status_code}"
        check(f"{a.key} unsealed and healthy", alive)
    check("identity issuer is its own URL", lambda: (http.get(url_of("identity") + "/.well-known/openid-configuration").json()["issuer"].rstrip("/") == url_of("identity"), ""))
    gw = ctx.gateway()
    for a in (x for x in stack.active() if x.llm):
        def chat(a=a):
            key = ctx.state.app(a.key).get("llm_key")
            ok, detail = gw.chat_test(key, m.llm.chat_alias) if key else (False, "no gateway key in the state file")
            return ok, f"{a.key} chat via {m.llm.chat_alias}: {detail}"
        check(f"{a.key} gateway chat call", chat)
    return out

